-- 2. MEMBER (회원)
--------------------------------------------------------------------------------
CREATE TABLE MEMBER (
    MEMBER_ID    NUMBER              NOT NULL,
    USER_ID      VARCHAR2(100 CHAR)  NOT NULL,
    USER_PW      VARCHAR2(200 CHAR)  NOT NULL,
    USER_NAME    VARCHAR2(100 CHAR)  NOT NULL,
    EMAIL        VARCHAR2(128 CHAR)  NOT NULL,
    PHONE        VARCHAR2(100 CHAR),
    USER_GRADE   CHAR(1)             DEFAULT 'M' NOT NULL,
    STATUS       CHAR(1)             DEFAULT 'Y' NOT NULL,
    JOIN_DATE    DATE                DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MEMBER            PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UQ_MEMBER_USER_ID    UNIQUE (USER_ID),
    CONSTRAINT CK_MEMBER_GRADE      CHECK (USER_GRADE IN ('M','A')),
    CONSTRAINT CK_MEMBER_STATUS     CHECK (STATUS IN ('Y','N'))
);

COMMENT ON TABLE  MEMBER              IS '회원';
COMMENT ON COLUMN MEMBER.MEMBER_ID    IS '회원 번호(PK)';
COMMENT ON COLUMN MEMBER.USER_ID      IS '로그인 아이디';
COMMENT ON COLUMN MEMBER.USER_PW      IS '비밀번호(해시 저장)';
COMMENT ON COLUMN MEMBER.USER_NAME    IS '이름/닉네임';
COMMENT ON COLUMN MEMBER.EMAIL        IS '이메일';
COMMENT ON COLUMN MEMBER.PHONE        IS '연락처';
COMMENT ON COLUMN MEMBER.USER_GRADE   IS 'M:일반회원, A:관리자';
COMMENT ON COLUMN MEMBER.STATUS       IS 'Y:정상, N:탈퇴';
COMMENT ON COLUMN MEMBER.JOIN_DATE    IS '가입일';


