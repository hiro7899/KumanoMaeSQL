-- 14. 지도 통합 조회용 VIEW (회원 제보 + 공식 뉴스/지자체 공지 통합)
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_MAP_MARKER AS
SELECT
    'USER'                 AS SOURCE_TYPE,
    BOARD_ID               AS TARGET_ID,
    TITLE,
    CASE WHEN CLEAR_YN = 'Y' THEN 'CLEARED' ELSE RISK_LEVEL END AS DISPLAY_RISK,
    LATITUDE, LONGITUDE, ADDRESS,
    SIGHTING_DATE          AS EVENT_DATE,
    REG_DATE
FROM BOARD
WHERE STATUS = 'Y'
UNION ALL
SELECT
    CASE WHEN SOURCE_TYPE = 'GOV' THEN 'OFFICIAL_GOV' ELSE 'OFFICIAL_NEWS' END,
    NEWS_ID,
    TITLE,
    NVL(RISK_LEVEL, 'CAUTION'),
    LATITUDE, LONGITUDE, REGION_TEXT,
    PUBLISHED_DATE,
    COLLECTED_DATE
FROM NEWS_ALERT
WHERE LATITUDE IS NOT NULL AND LONGITUDE IS NOT NULL;


