-- 3. BOARD (제보)
--------------------------------------------------------------------------------
CREATE TABLE BOARD (
    BOARD_ID       NUMBER              NOT NULL,
    MEMBER_ID      NUMBER              NOT NULL,
    TITLE          VARCHAR2(255 CHAR)  NOT NULL,
    CONTENT        CLOB                NOT NULL,
    RISK_LEVEL     VARCHAR2(20 CHAR)   NOT NULL,
    LATITUDE       NUMBER(10,7)        NOT NULL,
    LONGITUDE      NUMBER(10,7)        NOT NULL,
    ADDRESS        VARCHAR2(255 CHAR),
    SIGHTING_DATE  DATE                NOT NULL,
    SITUATION_TAG  VARCHAR2(255 CHAR),
    VIEW_CNT       NUMBER              DEFAULT 0 NOT NULL,
    STATUS         CHAR(1)             DEFAULT 'W' NOT NULL,
    CLEAR_YN       CHAR(1)             DEFAULT 'N' NOT NULL,
    CLEAR_DATE     DATE,
    CLEAR_MEMO     VARCHAR2(512 CHAR),
    REG_DATE       DATE                DEFAULT SYSDATE NOT NULL,
    MOD_DATE       DATE,
    CONSTRAINT PK_BOARD           PRIMARY KEY (BOARD_ID),
    CONSTRAINT FK_BOARD_MEMBER    FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT CK_BOARD_RISK      CHECK (RISK_LEVEL IN ('DANGER','WARNING','CAUTION')),
    CONSTRAINT CK_BOARD_STATUS    CHECK (STATUS IN ('W','Y','N')),
    CONSTRAINT CK_BOARD_CLEAR_YN  CHECK (CLEAR_YN IN ('Y','N'))
);

CREATE INDEX IDX_BOARD_RISK_STATUS ON BOARD (RISK_LEVEL, STATUS, CLEAR_YN);
CREATE INDEX IDX_BOARD_REGDATE     ON BOARD (REG_DATE);

COMMENT ON TABLE  BOARD                IS '제보(위험정보) 게시글';
COMMENT ON COLUMN BOARD.BOARD_ID       IS '제보 번호(PK)';
COMMENT ON COLUMN BOARD.MEMBER_ID      IS '작성자(FK→MEMBER)';
COMMENT ON COLUMN BOARD.TITLE          IS '제목';
COMMENT ON COLUMN BOARD.CONTENT        IS '상세 내용';
COMMENT ON COLUMN BOARD.RISK_LEVEL     IS '위험도: DANGER/WARNING/CAUTION';
COMMENT ON COLUMN BOARD.LATITUDE       IS '위도';
COMMENT ON COLUMN BOARD.LONGITUDE      IS '경도';
COMMENT ON COLUMN BOARD.ADDRESS        IS 'Geocoder 자동 변환 주소';
COMMENT ON COLUMN BOARD.SIGHTING_DATE  IS '목격 일시';
COMMENT ON COLUMN BOARD.SITUATION_TAG  IS '목격 당시 상황 태그(콤마 구분)';
COMMENT ON COLUMN BOARD.VIEW_CNT       IS '조회수';
COMMENT ON COLUMN BOARD.STATUS         IS 'W:승인대기, Y:승인, N:반려';
COMMENT ON COLUMN BOARD.CLEAR_YN       IS '위험 해제 여부(Y=안심마커 전환)';
COMMENT ON COLUMN BOARD.CLEAR_DATE     IS '위험 해제 처리일';
COMMENT ON COLUMN BOARD.CLEAR_MEMO     IS '위험 해제 사유';
COMMENT ON COLUMN BOARD.REG_DATE       IS '등록일';
COMMENT ON COLUMN BOARD.MOD_DATE       IS '수정일';


